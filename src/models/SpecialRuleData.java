package models;

public class SpecialRuleData {
    private String type;
    private String target;
    private String value;
    private String description;

    public String getType() {
        return type;
    }

    public String getTarget() {
        return target;
    }

    public String getValue() {
        return value;
    }

    public String getDescription() {
        return description;
    }
}
